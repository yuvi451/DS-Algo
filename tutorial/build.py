#!/usr/bin/env python3
"""Bundle tutorial/lessons/*.md into tutorial/assets/content.js.

Each lesson starts with a small header:

    ---
    title: Bind to a port
    module: First TCP server
    time: 20 min
    ---

Inside a lesson, a line `@include <path> [first-last] [title=...]` is replaced
by a fenced code block holding that file (paths are relative to tutorial/),
so lessons always show the exact code that check.sh verified.

usage: python3 tutorial/build.py
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
LANGS = {".cpp": "cpp", ".h": "cpp", ".sh": "bash", "Makefile": "make"}


def include(match):
    path, first, last, title = match.group(1), match.group(2), match.group(3), match.group(4)
    file = (HERE / path).resolve()
    lines = file.read_text().rstrip("\n").split("\n")
    if first:
        lines = lines[int(first) - 1:int(last)]
    lang = LANGS.get(file.suffix) or LANGS.get(file.name, "text")
    # tutorial/code/d-protocol/s2/src/protocol.h -> src/protocol.h
    shown = title or re.sub(r"^tutorial/code/[^/]+/(s\d+/)?", "", str(file.relative_to(HERE.parent)))
    return f"```{lang} title={shown}\n" + "\n".join(lines) + "\n```"


def parse(md_file):
    text = md_file.read_text()
    header, body = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S).groups()
    meta = {k: v.strip('"') for k, v in (line.split(": ", 1) for line in header.strip().split("\n"))}
    body = re.sub(r"^@include (\S+)(?: (\d+)-(\d+))?(?: title=(.+))?$", include, body, flags=re.M)
    return {"id": md_file.stem.split("-", 1)[1], **meta, "body": body}


lessons = [parse(f) for f in sorted((HERE / "lessons").glob("*.md"))]
out = HERE / "assets" / "content.js"
out.write_text("// Generated by build.py. Edit lessons/*.md instead.\nwindow.LESSONS = "
               + json.dumps(lessons, indent=1) + ";\n")
print(f"wrote {len(lessons)} lessons to {out.relative_to(HERE.parent)}")
